const { chromium } = require(process.env.RADIO_PLAYWRIGHT_PATH || "playwright");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { pathToFileURL } = require("node:url");

(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.RADIO_BROWSER_PATH || undefined });
  try {
    const context = await browser.newContext({ reducedMotion: "reduce", viewport: { width: 1366, height: 768 } });
    const page = await context.newPage();
    await page.clock.install();
    await page.clock.pauseAt(new Date());
    const errors = [];
    page.on("pageerror", (error) => errors.push(error.message));
    const url = (file) => pathToFileURL(path.join(__dirname, "..", file.split("?")[0])).href + (file.includes("?") ? `?${file.split("?")[1]}` : "");
    const open = (file) => page.goto(url(file));
    await open("index.html");
    assert.equal(await page.locator("#home-title").innerText(), "A 类题库");
    assert.equal(await page.locator(".entry-card").count(), 5);
    assert.equal(await page.locator(".home-dashboard progress").count(), 2);
    assert.equal(await page.locator("#answered-count").innerText(), "0");
    assert.equal(await page.locator("#mastered-count").innerText(), "0");
    assert.equal(await page.locator(".site-header nav").count(), 0, "移除顶部重复导航");
    await page.locator(".brand").focus();
    await page.keyboard.press("Tab");
    assert.equal(await page.locator(".entry-card").first().evaluate((node) => node === document.activeElement), true);
    assert.equal(await page.locator(".entry-card").first().evaluate((node) => getComputedStyle(node).outlineColor), "rgb(128, 169, 154)", "键盘焦点使用柔和绿色");
    await page.locator('.entry-card[href="practice.html"]').click();
    assert.equal(await page.locator("#question-number").innerText(), "第 001 题", "顺序练习直接做题");
    assert.equal(await page.locator("progress, .site-header nav").count(), 0);
    await page.locator("#open-question-navigation").click();
    await page.locator("#jump-input").fill("3");
    await page.locator("#jump-form button").click();
    assert.equal(await page.locator("#question-number").innerText(), "第 003 题");
    await page.locator('#options input[value="B"]').check();
    await page.locator("#toggle-favorite").click();
    await page.locator("#back-to-list").click();
    assert.equal(await page.locator("#incorrect-count").innerText(), "1");
    assert.equal(await page.locator("#remaining-count").innerText(), "682");
    assert.equal(await page.locator("#progress").getAttribute("value"), "1");
    await page.locator('.entry-card[href="practice.html"]').click();
    assert.equal(await page.locator("#question-number").innerText(), "第 003 题", "直接恢复上次练习位置");
    await open("index.html?collection=mistakes");
    await page.waitForURL(/practice\.html/);
    assert.equal(await page.locator("#question-number").innerText(), "第 001 题");
    assert.deepEqual(await page.locator("#question-nav button").allTextContents(), ["1"]);
    assert.match(await page.locator("#source-id").innerText(), /题库第 3 题/);
    await open("index.html?collection=favorites");
    await page.waitForURL(/practice\.html/);
    assert.equal(await page.locator("#question-card").isVisible(), true);
    assert.equal(await page.locator("#toggle-favorite").getAttribute("aria-pressed"), "true");
    await open("index.html?view=groups");
    const guide = await page.evaluate(() => window.STUDY_GUIDE);
    const expandRange = (label) => label.replace(/^第 | 题$/g, "").split("、").flatMap((part) => {
      const [start, end = start] = part.split("–").map(Number);
      return Array.from({ length: end - start + 1 }, (_, index) => start + index);
    });
    assert.equal(await page.locator(".topic-list-row").count(), 13);
    assert.equal(await page.locator(".group-list-row").count(), 0, "先展示主题，暂不展示记忆组");
    const topicRanges = await page.locator(".topic-list-row .list-range").allTextContents();
    let groupCount = 0;
    for (const [index, topic] of guide.topics.entries()) {
      const groups = guide.groups.filter((group) => group.topic_id === topic.id);
      assert.deepEqual(expandRange(topicRanges[index]), groups.flatMap((group) => group.question_numbers).sort((a, b) => a - b), `${topic.id} 主题题号范围准确`);
      await page.locator(".topic-list-row").nth(index).click();
      assert.equal(await page.locator("#library-title").innerText(), topic.title);
      assert.equal(await page.locator(".topic-list-row").count(), 0);
      assert.equal(await page.locator(".group-list-row").count(), groups.length);
      const rows = await page.locator(".group-list-row").evaluateAll((nodes) => nodes.map((node) => ({ href: node.getAttribute("href"), range: node.querySelector(".list-range").textContent })));
      groups.forEach((group, groupIndex) => {
        assert.equal(rows[groupIndex].href, `study.html?topic=${topic.id}#group-${group.id}`);
        assert.deepEqual(expandRange(rows[groupIndex].range), [...group.question_numbers].sort((a, b) => a - b), `${group.id} 记忆组题号范围准确`);
      });
      groupCount += rows.length;
      await page.reload();
      assert.equal(await page.locator("#library-title").innerText(), topic.title, "刷新保留所选主题");
      await page.locator("#library-back").click();
      assert.equal(await page.locator(".topic-list-row").count(), 13, "返回全部主题");
    }
    assert.equal(groupCount, 70);
    await page.locator(".topic-list-row").first().click();
    await page.goBack();
    assert.equal(await page.locator(".topic-list-row").count(), 13, "浏览器后退恢复主题列表");
    await page.locator(".topic-list-row").first().click();
    await page.locator(".group-list-row").nth(2).click();
    assert.equal(await page.locator("#group-g03").isVisible(), true);
    await page.locator("#study-back").click();
    assert.equal(await page.locator(".group-list-row").count(), 8, "详情返回当前主题的记忆组");
    await page.locator(".group-list-row").nth(2).click();
    assert.equal(await page.locator("progress, .site-header nav").count(), 0);
    await page.locator("#group-g03 .master-button").click();
    await page.locator(".brand").click();
    assert.equal(await page.locator("#mastered-count").innerText(), "1");
    assert.equal(await page.locator("#study-progress").getAttribute("value"), "1");
    await page.reload();
    assert.equal(await page.locator("#mastered-count").innerText(), "1", "首页掌握进度跨刷新保留");
    await open("index.html?view=questions");
    await page.waitForURL(/practice\.html/);
    assert.equal(await page.locator("#question-number").innerText(), "第 003 题", "旧列表入口也直接做题");
    await open("index.html?question=6");
    await page.waitForURL(/practice\.html\?question=6/);
    assert.equal(await page.locator("#question-number").innerText(), "第 006 题", "旧题目书签保持可用");
    await open("index.html?topic=rules");
    await page.waitForURL(/practice\.html\?topic=rules/);
    assert.match(await page.locator("#page-position").innerText(), /\/ 69$/, "旧主题练习书签保持可用");
    await open("practice.html?question=1");
    await page.locator('#options input[value="A"]').check();
    const background = (selector) => page.locator(selector).evaluate((node) => getComputedStyle(node).backgroundColor);
    await page.waitForFunction(() => getComputedStyle(document.querySelector(".option:has(input:checked)")).backgroundColor === "rgb(232, 241, 255)");
    assert.equal(await background(".option:has(input:checked)"), "rgb(232, 241, 255)");
    await page.locator('#options input[value="B"]').check();
    await page.locator("#check-answer").click();
    await page.waitForFunction(() => getComputedStyle(document.querySelector(".option.is-wrong")).backgroundColor === "rgb(251, 227, 223)");
    assert.equal(await background(".option.is-correct:has(input:checked)"), "rgb(238, 246, 238)");
    assert.equal(await background(".option.is-wrong"), "rgb(251, 227, 223)");

    fs.mkdirSync(path.join(__dirname, "../tmp/navigation"), { recursive: true });
    for (const file of ["index.html", "index.html?view=groups", ...guide.topics.map((topic) => `index.html?view=groups&topic=${topic.id}`), "practice.html?collection=mistakes", "practice.html?collection=favorites"]) {
      for (const width of [320, 390, 768, 1366]) {
        await page.setViewportSize({ width, height: 844 });
        await open(file);
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `${file} 在 ${width} 不应横向溢出`);
      }
    }
    await open("index.html");
    await page.screenshot({ path: path.join(__dirname, "../tmp/navigation/home-desktop.png"), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.locator(".site-header").evaluate((node) => node.getBoundingClientRect().top), 0, "手机首页导航应位于顶部");
    await page.screenshot({ path: path.join(__dirname, "../tmp/navigation/home-mobile.png"), fullPage: true });
    await open("index.html?view=groups");
    await page.screenshot({ path: path.join(__dirname, "../tmp/navigation/topics-mobile.png"), fullPage: true });
    await page.locator(".topic-list-row").first().click();
    await page.screenshot({ path: path.join(__dirname, "../tmp/navigation/groups-mobile.png"), fullPage: true });
    await page.setViewportSize({ width: 1366, height: 844 });
    await page.screenshot({ path: path.join(__dirname, "../tmp/navigation/groups-desktop.png"), fullPage: true });

    const touch = await browser.newContext({ reducedMotion: "reduce", viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
    const mobile = await touch.newPage();
    mobile.on("pageerror", (error) => errors.push(error.message));
    const cdp = await touch.newCDPSession(mobile);
    const swipe = async (selector, dx, dy = 0) => {
      const box = await mobile.locator(selector).boundingBox();
      const x = dx < 0 ? box.x + box.width - 30 : box.x + 30;
      const y = box.y + Math.min(box.height / 2, 25);
      await cdp.send("Input.dispatchTouchEvent", { type: "touchStart", touchPoints: [{ x, y }] });
      for (let step = 1; step <= 6; step++) await cdp.send("Input.dispatchTouchEvent", { type: "touchMove", touchPoints: [{ x: x + dx * step / 6, y: y + dy * step / 6 }] });
      await cdp.send("Input.dispatchTouchEvent", { type: "touchEnd", touchPoints: [] });
    };
    await mobile.goto(url("practice.html?question=3"));
    const position = () => mobile.locator("#page-position").innerText();
    await swipe("#options .option:first-of-type .option-text", -160);
    assert.equal(await position(), "4 / 683", "真实触屏左滑下一题");
    assert.equal(await mobile.locator("#options input:checked").count(), 0, "滑动选项不会误选答案");
    await swipe("#question-title", 160);
    assert.equal(await position(), "3 / 683", "右滑上一题");
    await swipe("#question-title", -20);
    assert.equal(await position(), "3 / 683", "短距离触摸不切题");
    await swipe("#question-title", 10, -100);
    assert.equal(await position(), "3 / 683", "上下滚动不切题");
    await mobile.locator("#toggle-hint").click();
    await swipe("#question-hint", -120);
    assert.equal(await position(), "3 / 683", "提示弹窗内滑动不切题");
    await mobile.screenshot({ path: path.join(__dirname, "../tmp/navigation/hint-mobile.png") });
    await mobile.locator("#close-hint").click();
    await mobile.goto(url("practice.html?question=1"));
    await swipe("#question-title", 160);
    assert.equal(await position(), "1 / 683", "第一题右滑不越界");
    await mobile.goto(url("practice.html?question=683"));
    await swipe("#question-title", -160);
    assert.equal(await position(), "683 / 683", "最后一题左滑不越界");
    await mobile.goto(url("practice.html?exam=1"));
    await mobile.locator("#start-exam").click();
    await mobile.locator("#options input").first().check();
    const exam = await mobile.evaluate(() => JSON.parse(localStorage.getItem("radio-a-exam-v1")));
    await swipe("#question-title", -160);
    assert.equal(await position(), "2 / 40", "考试中也支持滑动");
    await swipe("#question-title", 160);
    assert.equal(await mobile.locator("#options input:checked").count(), 1, "滑动后保留原题作答");
    await mobile.reload();
    assert.equal((await mobile.evaluate(() => JSON.parse(localStorage.getItem("radio-a-exam-v1")))).exam.deadline, exam.exam.deadline);
    assert.deepEqual(errors, []);
    console.log("PASS: 首页双进度卡、顺序练习直接进入及恢复、无顶部重复导航、柔和键盘焦点、13 主题逐级查看 70 分组及全部精确题号范围、刷新与返回、错题收藏往返、旧入口、蓝色选中及红绿判分、四种屏宽、真实触屏滑动及考试进度。");
    await touch.close();
  } finally {
    await browser.close();
  }
})().catch((error) => { console.error(error); process.exitCode = 1; });
