const { chromium } = require(process.env.RADIO_PLAYWRIGHT_PATH || "playwright");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { pathToFileURL } = require("node:url");

(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.RADIO_BROWSER_PATH || undefined });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1200 } });
    const errors = [];
    page.on("pageerror", (error) => errors.push(error.message));
    const url = (file) => pathToFileURL(path.join(__dirname, "..", file.split("?")[0])).href + (file.includes("?") ? "?" + file.split("?")[1] : "");
    const open = (file) => page.goto(url(file));
    const navNumbers = () => page.locator("#question-nav button").allTextContents();
    await open("study.html");
    await page.evaluate(() => localStorage.clear());
    await page.reload();
    const guide = await page.evaluate(() => window.STUDY_GUIDE);
    assert.equal(guide.groups.length, 70);
    assert.equal(guide.topics.length, 13);
    assert.deepEqual(guide.groups.flatMap((g) => g.question_numbers).sort((a, b) => a - b), Array.from({ length: 683 }, (_, i) => i + 1));
    assert.equal(await page.locator("#topic-nav button").count(), 13);
    assert.equal(await page.locator(".knowledge-card").count(), 8);
    await page.locator("#group-g01 .master-button").click();
    assert.equal(await page.locator("#mastered-count").innerText(), "1");
    await page.reload();
    assert.equal(await page.locator("#group-g01 .master-button").getAttribute("aria-pressed"), "true");
    await page.locator("#only-unmastered").check();
    assert.equal(await page.locator(".knowledge-card").count(), 7);
    await page.locator("#only-unmastered").uncheck();
    await page.locator("#group-g01 .master-button").click();
    for (const topic of guide.topics) {
      await page.locator(`#topic-${topic.id}`).click();
      assert.equal(await page.locator("#topic-title").innerText(), topic.title);
      assert.equal(await page.locator(".knowledge-card").count(), topic.group_ids.length);
    }
    await page.locator("#study-search").fill("AGC");
    assert.equal(await page.locator("#group-g42").count(), 1);
    assert.equal(await page.locator("#group-g55").count(), 1);
    await page.locator("#topic-receivers").click();
    await page.locator("#group-g58 .knowledge-details > summary").click();
    assert.match(await page.locator("#group-g58").innerText(), /端电压/);
    await page.locator("#group-g58 .source-questions > summary").click();
    assert.equal(await page.locator("#group-g58 .source-question").count(), 14);
    await page.locator("#group-g58 .group-practice").click();
    assert.equal(await page.locator("#question-nav button").count(), 14);
    assert.equal(await page.locator("#question-number").innerText(), "第 555 题");
    await open("index.html?group=g01&question=22");
    assert.deepEqual(await navNumbers(), guide.groups[0].question_numbers.map(String));
    assert.equal(await page.locator("#question-number").innerText(), "第 022 题");
    assert.equal(await page.locator("#next-question").isDisabled(), true);
    await page.locator("#jump-input").fill("13");
    await page.locator("#jump-form button").click();
    assert.equal(await page.locator("#jump-input").evaluate((input) => input.validity.valid), false);
    await page.locator("#jump-input").fill("21");
    await page.locator("#jump-form button").click();
    assert.equal(await page.locator("#question-number").innerText(), "第 021 题");
    await open("index.html?topic=callsigns");
    assert.equal(await page.locator("#question-nav button").count(), 29);
    assert.equal(await page.locator("#question-number").innerText(), "第 070 题");
    await open("index.html?day=3");
    assert.equal(await page.locator("#question-nav button").count(), 62);
    assert.equal((await navNumbers()).at(-1), "683");
    await open("index.html?mixed=1");
    const mixed = await page.evaluate(() => [...document.querySelectorAll("#question-nav button")].map((button) => window.QUESTION_BANK[Number(button.textContent) - 1]));
    assert.equal(mixed.length, 40);
    assert.equal(new Set(mixed.map((q) => q.id)).size, 40);
    assert.equal(mixed.filter((q) => q.answers.length === 1).length, 32);
    assert.equal(mixed.filter((q) => q.answers.length > 1).length, 8);
    await open("index.html");
    assert.deepEqual(await navNumbers(), Array.from({ length: 683 }, (_, i) => String(i + 1)));
    assert.equal(await page.locator("#check-answer").isDisabled(), true);
    await page.locator('#options input[value="A"]').check();
    await page.locator("#check-answer").click();
    assert.match(await page.locator("#feedback").innerText(), /回答错误/);
    await page.locator("#retry-answer").click();
    for (const key of ["A", "C"]) await page.locator(`#options input[value="${key}"]`).check();
    await page.locator("#check-answer").click();
    assert.match(await page.locator("#feedback").innerText(), /回答正确/);
    await open("index.html?question=3");
    await page.locator('#options input[value="B"]').check();
    await page.locator('#options input[value="A"]').check();
    assert.equal(await page.locator("#options input:checked").count(), 1);
    await page.locator("#check-answer").click();
    assert.match(await page.locator("#feedback").innerText(), /回答正确/);
    await open("study.html?topic=antennas");
    await page.locator("#group-g45 .knowledge-details > summary").click();
    await page.evaluate(() => window.scrollTo(0, 0));
    fs.mkdirSync(path.join(__dirname, "../tmp/study"), { recursive: true });
    await page.screenshot({ path: path.join(__dirname, "../tmp/study/desktop.png"), fullPage: true });
    for (const width of [375, 390, 768, 1000, 1440]) {
      await page.setViewportSize({ width, height: 900 });
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false, `study overflow at ${width}`);
    }
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.locator("#topic-menu").evaluate((menu) => menu.open), false);
    await page.locator("#topic-menu > summary").click();
    await page.locator("#topic-electricity").click();
    assert.equal(await page.locator("#topic-title").innerText(), "电学、单位、电源与测量");
    assert.equal(await page.locator("#topic-menu").evaluate((menu) => menu.open), false);
    await page.locator("#group-g65 .knowledge-details > summary").click();
    await page.locator("#group-g65").scrollIntoViewIfNeeded();
    await page.screenshot({ path: path.join(__dirname, "../tmp/study/mobile.png") });
    await open("index.html?group=g65&question=647");
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
    assert.equal(await page.locator("#question-number").innerText(), "第 647 题");
    await open("study.html");
    await page.evaluate(() => localStorage.setItem("radio-a-mastered-groups-v1", JSON.stringify(["g01", "invalid"])));
    await page.reload();
    assert.equal(await page.locator("#mastered-count").innerText(), "1");
    assert.deepEqual(errors, []);
    console.log("PASS: all 683 mappings; all 13 categories; mastery persistence/filtering; cross-topic search; source answers; filtered/global numbering; group/topic/day links; 32+8 random selection; single/multi grading; offline loading; mobile menu; five viewport widths; no browser errors.");
  } finally {
    await browser.close();
  }
})().catch((error) => { console.error(error); process.exitCode = 1; });
